-- Журнал смены статусов завели в миграции 001, но писать в него начали только
-- сейчас. Заявки, созданные до этого, остались бы без единой записи, и выглядело
-- бы так, будто их никто не создавал.
--
-- Поэтому дописываем каждой существующей заявке первую строку: «появилась в
-- таком-то статусе». Прежнего статуса нет — значит from_status пуст. Автор не
-- диспетчер, а сама система, потому что в момент создания никто не нажимал
-- кнопку «отклонить»: решение не принималось.
--
-- В comment копируем текущую причину: иначе у отклонённых заявок она
-- потерялась бы при первом же изменении статуса — ровно тот случай, ради
-- которого журнал и нужен.

INSERT INTO request_status_history (request_id, from_status, to_status, changed_by, comment, changed_at)
SELECT id, '', status, 'system', NULLIF(comment, ''), created_at
FROM requests
WHERE NOT EXISTS (
    SELECT 1 FROM request_status_history h WHERE h.request_id = requests.id
);
